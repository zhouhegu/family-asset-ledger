function resolveLanguage(saved, browserLanguage) {
  if (saved === 'zh-CN' || saved === 'en') return saved;
  return /^zh(?:-|$)/i.test(browserLanguage || '') ? 'zh-CN' : 'en';
}
function loadLanguage() {
  let saved = null;
  try { saved = localStorage.getItem(LANGUAGE_KEY); } catch { /* Session-only fallback. */ }
  const preferred = typeof navigator === 'undefined' ? 'zh-CN' : navigator.language;
  return resolveLanguage(saved, preferred);
}
let language = loadLanguage();
function t(message, values = []) {
  message = String(message ?? '');
  const translated = language === 'en' && Object.prototype.hasOwnProperty.call(EN_MESSAGES, message) ? EN_MESSAGES[message] : message;
  return translated.replace(/\{(\d+)\}/g, (match, index) => index < values.length ? String(values[index]) : match);
}
function numberLocale() { return language === 'en' ? 'en-US' : 'zh-CN'; }
function compactAmount(amount) {
  if (language === 'en') return new Intl.NumberFormat('en-US', {notation:'compact', maximumFractionDigits:1}).format(amount);
  return Math.abs(amount) >= 10000 ? `${(amount / 10000).toFixed(0)}万` : amount.toFixed(0);
}
function translateStaticPage() {
  document.documentElement.lang = language;
  document.querySelectorAll('[data-i18n]').forEach(el => { el.textContent = t(el.dataset.i18n); });
  for (const attribute of ['title', 'placeholder', 'aria-label']) {
    document.querySelectorAll(`[data-i18n-${attribute}]`).forEach(el => {
      el.setAttribute(attribute, t(el.getAttribute(`data-i18n-${attribute}`)));
    });
  }
  document.getElementById('languageSelect').value = language;
}
